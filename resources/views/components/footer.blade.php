    <script>
        let productToDelete = null;
        let cartItemElement = null;

        // Handle close cart button with event delegation (works after HTML reload)
        $(document).on('click', '.close_cart', function(e){
            e.preventDefault();
            $("body").removeClass("cart-opened");
        });

        function positionModal($element) {
            // Find the parent product div
            let $productDiv = $element.closest(".product");

            if ($productDiv.length === 0) {
                return;
            }

            let productOffset = $productDiv.offset();
            let productWidth = $productDiv.outerWidth();
            let productHeight = $productDiv.outerHeight();

            let modalDialog = $("#confirmDeleteModalDialog");
            let modalContent = $("#confirmDeleteModalContent");

            // Set modal to same size and position as product div
            modalDialog.css({
                'top': productOffset.top + 'px',
                'left': productOffset.left + 'px',
                'width': productWidth + 'px',
                'height': productHeight + 'px'
            });

            modalContent.css({
                'width': '100%',
                'height': '100%'
            });
        }

        $(".cart_remove").click(function(e){
            e.preventDefault();

            productToDelete = $(this).attr("product_id");
            cartItemElement = $(this);

            // Position and show modal
            positionModal($(this));
            $("#confirmDeleteModal").modal("show");
        });

        // Handle Cancel button
        $(document).on('click', '#cancelDeleteBtn', function(e){
            e.preventDefault();
            productToDelete = null;
            cartItemElement = null;
            $("#confirmDeleteModal").modal("hide");
        });

        // Also handle when modal is closed by backdrop or ESC
        $("#confirmDeleteModal").on('hidden.bs.modal', function(){
            productToDelete = null;
            cartItemElement = null;
        });

        // Handle Remove button
        $("#confirmDeleteBtn").click(function(){
            if(productToDelete && cartItemElement){
                let _token =  "{{ csrf_token() }}";

                // Hide modal first
                $("#confirmDeleteModal").modal("hide");

                // Remove product immediately from view
                cartItemElement.closest(".product").fadeOut(300, function(){
                    $(this).remove();
                });

                // Send delete request
                $.ajax({
                    url: "{{ route("porto.remove.cart") }}" ,
                    method : "post" ,
                    data : {
                        product_id: productToDelete , _token
                    } , success:(data)=>{
                        $(".nums_in_cart").html(data)

                        // Remove product from cart page if exists
                        $("tr.product-row[data-product-id='" + productToDelete + "']").fadeOut(300, function(){
                            $(this).remove();

                            // Check if cart is empty
                            if($("tbody tr.product-row").length === 0){
                                $("tbody").html('<tr><td colspan="5" class="text-center"><p class="mb-0">Your cart is empty.</p><a href="{{ route("porto.index") }}" class="btn btn-primary mt-3">Continue Shopping</a></td></tr>');
                            }
                        });

                        // Reload cart dropdown to update total
                        $(".dropdown-menu").load(location.href + " .dropdown-menu", function () {
                            $(".cart_remove").click(function(e){
                                e.preventDefault();
                                productToDelete = $(this).attr("product_id");
                                cartItemElement = $(this);
                                positionModal($(this));
                                $("#confirmDeleteModal").modal("show");
                            });

                            // Reattach close cart handler after reload
                            $(".close_cart").off('click').on('click', function(e){
                                e.preventDefault();
                                $("body").removeClass("cart-opened");
                            });
                        });
                    }
                });

                // Reset variables
                productToDelete = null;
                cartItemElement = null;
            }
        });
    </script>
